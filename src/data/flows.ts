import type { Flow, FlowNode, FlowResult } from './types'

/**
 * Diagnostic flows ("Какво прави колата?").
 * Every flow only NARROWS the possibilities – results are directions for checking, never a diagnosis.
 */

const q = (id: string, question: string, options: [label: string, next: string][], hint?: string): FlowNode => ({
  id,
  question,
  ...(hint ? { hint } : {}),
  options: options.map(([label, next]) => ({ label, next })),
})

const r = (id: string, result: FlowResult): FlowNode => ({ id, result })

const nodes = (...list: FlowNode[]): Record<string, FlowNode> =>
  Object.fromEntries(list.map((n) => [n.id, n]))

