const MISFIRE_SOURCES = ['haynes-p0300', 'underhood-misfire', 'cr-cel', 'aa-eml']

function cylinderMisfire(n: number): ObdCode {
  const others = [1, 2, 3, 4, 5, 6].filter((c) => c !== n).slice(0, 2)
  return {
    code: `P030${n}`,
    titleEn: `Cylinder ${n} Misfire Detected`,
    titleBg: `Открито пропускане на запалването в цилиндър ${n}`,
    system: 'Запалване / пропускания',
    summary: `Компютърът е отчел, че цилиндър ${n} не изгаря сместа нормално. Кодът посочва цилиндъра, но не и коя част е виновна – причината може да е запалване, гориво, въздух или механика.`,
    causes: MISFIRE_CAUSES,
    symptoms: MISFIRE_SYMPTOMS,
    diagnosis: MISFIRE_DIAG,
    urgency: 'soon',
    urgencyContext: MISFIRE_URGENCY,
    dontDo: [
      `Не сменяй бобината на цилиндър ${n} само заради кода – първо направи тест с размяна`,
      ...MISFIRE_DONT.slice(0, 2),
    ],
    related: [
      'obd/p0300',
      ...others.map((c) => `obd/p030${c}`),
      'obd/p0351',
      'symptoms/engine-misfire',
      'symptoms/engine-shaking-idle',
      'dashboard/check-engine',
      'guides/check-engine',
    ],
    keywords: [
      `p030${n}`,
      `грешка p030${n}`,
      `пропускане цилиндър ${n}`,
      `cylinder ${n} misfire`,
      `p030${n} golf`,
      `p030${n} бобина`,
      'тресе на празен ход',
      'работи на 3 цилиндъра',
      'код за пропускане',
    ],
    sources: MISFIRE_SOURCES,
  }
}

